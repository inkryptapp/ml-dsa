#!/usr/bin/env node
// Writes src/mldsa87-wasm.ts, the committed artifact module (ADR 0004), from a built .wasm:
//   node scripts/generate-artifact.mjs <path to mldsa87.wasm>
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const [input] = process.argv.slice(2);
if (input === undefined) {
  console.error("usage: node scripts/generate-artifact.mjs <path to mldsa87.wasm>");
  process.exit(1);
}

const wasm = await readFile(input);
const sha256 = createHash("sha256").update(wasm).digest("hex");
const output = fileURLToPath(new URL("../src/mldsa87-wasm.ts", import.meta.url));
await writeFile(
  output,
  [
    "// Generated by scripts/generate-artifact.mjs through `pnpm build:wasm`. Do not edit.",
    `// The module is ${wasm.length} bytes with SHA-256 ${sha256}.`,
    // Typed as string so that tsc doesn't repeat the literal in the declaration file.
    `export const MLDSA87_WASM_BASE64: string = "${wasm.toString("base64")}";`,
    "",
  ].join("\n"),
);
console.log(`wrote src/mldsa87-wasm.ts (${wasm.length} bytes, sha256 ${sha256})`);
